require('dotenv').config({ path: require('path').resolve(__dirname, '../../../.env') });

const { sequelize, Sequelize } = require('../models');

async function ensureColumn(tableName, columnName, definition) {
  const queryInterface = sequelize.getQueryInterface();
  const table = await queryInterface.describeTable(tableName);

  if (table[columnName]) {
    console.log(`- ${tableName}.${columnName} already exists`);
    return;
  }

  await queryInterface.addColumn(tableName, columnName, definition);
  console.log(`+ Added ${tableName}.${columnName}`);
}

async function migrate() {
  await sequelize.authenticate();

  // Conversation ownership for the inbox. Nullable so existing rows stay
  // unassigned; the inbox shows who currently owns each chat and lets agents
  // reassign it.
  await ensureColumn('customers', 'assigned_agent_id', {
    type: Sequelize.UUID,
    allowNull: true,
  });
}

migrate()
  .then(async () => {
    console.log('Customer assignee migration complete');
    await sequelize.close();
    process.exit(0);
  })
  .catch(async (err) => {
    console.error(err);
    try {
      await sequelize.close();
    } catch {}
    process.exit(1);
  });
